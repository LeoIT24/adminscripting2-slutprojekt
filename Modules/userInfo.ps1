Write-Host "=== User Information ===" -ForegroundColor Cyan
Write-Host ""

Write-Host "Username:" -ForegroundColor Yellow
Write-Host $env:USERNAME

Write-Host ""
Write-Host "Domain:" -ForegroundColor Yellow
Write-Host $env:USERDOMAIN

# -----------------------------
# Loggning
# -----------------------------

# Skapar loggmappen om den saknas
if (-not (Test-Path "..\logs")) {
    New-Item -ItemType Directory -Path "..\logs" | Out-Null
}

# Namnet på modulen
$ModuleName = "System Information"

# Skapar loggrad
$timestamp = Get-Date -Format "yyyy-MM-dd HH:mm:ss"

$logEntry = "$timestamp | User: $env:USERNAME | Module: $ModuleName"

# Sparar till loggfil
Add-Content `
    -Path "..\logs\activity.log" `
    -Value $logEntry

Write-Host "Log entry created." -ForegroundColor Green